# Escribe un programa que calcule el área de un rectángulo a partir de su base y altura.


print("CALCULO DE ÁREA")
print("---------------")
base = float(input("Introduce la base del rectángulo: "))
altura = float(input("Introduce la altura del rectángulo: "))

print("RESULTADO: El área del rectángulo es: ", base * altura, "cm^2.")